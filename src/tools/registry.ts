export interface Tool {
  /** URL segment: the tool lives at #/<slug>. */
  slug: string
  title: string
  description: string
  icon: LucideIcon
  /** Accepted input → produced output, shown as chips on the card. */
  formats: string
  /** Optional short label on the card, e.g. "Baru". */
  badge?: string
  /** Which group the tool is listed under on the home page. */
  category: CategoryId
  /** Extra words people search with (file extensions, everyday terms). */
  keywords: string[]
  /** Lazy so each tool's libraries load only when that tool is opened. */
  component: LazyExoticComponent<ComponentType>
  /** The tool as an installable npm package (packages/<dir>/), shown under "Pasang di situsmu". */
  package?: ToolPackage
}

export interface ToolPackage {
  /** npm name, e.g. "@chalidade/screen-recorder". */
  name: string
  /** The custom element it registers, e.g. "screen-recorder". */
  element: string
  /** Folder under packages/ (for the README link). */
  dir: string
  /** Live on npm yet? Until then only the iframe embed is offered. */
  published: boolean
}

