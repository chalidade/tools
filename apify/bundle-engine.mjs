// Bundles part of the site's own tool source (src/) into an Actor's
// src/engine.js, so an Actor runs the very engine the browser tool runs.
// Apify builds each Actor folder on its own, so the bundle is committed.
//
//   node apify/<actor>/build-engine.mjs            (from the repo root, after npm install)
//   TOOWL_SRC=/path/to/src node apify/<actor>/build-engine.mjs
//
// Browser-only bits are swapped out: Vite `?url` assets become "", the UI
// language is English, and onnxruntime-web is replaced by onnxruntime-node
// (same API; the Actor installs it).
import { build } from 'esbuild'
import path from 'node:path'

export async function bundleEngine({ here, entry = 'engine/entry.ts', external = [], name }) {
  const src = path.resolve(process.env.TOOWL_SRC ?? path.join(here, '../../src'))
  const stubs = {
    name: 'node-stubs',
    setup(b) {
      b.onResolve({ filter: /\?url$/ }, (a) => ({ path: a.path, namespace: 'stub' }))
      b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({ contents: 'export default ""', loader: 'js' }))
      b.onResolve({ filter: /^@\/lib\/i18n$/ }, () => ({ path: 'i18n', namespace: 'i18n' }))
      b.onLoad({ filter: /.*/, namespace: 'i18n' }, () => ({
        contents: 'export const tr = (_id, en) => en; export const locale = () => "en-US"',
        loader: 'js',
      }))
      b.onResolve({ filter: /^onnxruntime-web(\/.*)?$/ }, () => ({ path: 'onnxruntime-node', external: true }))
      b.onResolve({ filter: /^@\// }, async (a) => b.resolve('./' + a.path.slice(2), { resolveDir: src, kind: a.kind }))
    },
  }
  await build({
    entryPoints: [path.join(here, entry)],
    outfile: path.join(here, 'src/engine.js'),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    external,
    resolveExtensions: ['.ts', '.js', '.mjs', '.tsx', '.json'],
    plugins: [stubs],
    legalComments: 'none',
    banner: { js: `// GENERATED by build-engine.mjs from the toowl site source (${name}). Do not edit.\n` },
    logLevel: 'info',
  })
}
