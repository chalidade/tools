// Bundles the site's PDF → Word and PDF → Excel engines
// (src/tools/pdf-to-word, src/tools/pdf-to-excel) into src/engine.js for this Actor.
// Apify builds this folder on its own, so the bundle is committed.
// Run from the repo root after `npm install`: node apify/pdf-to-office/build-engine.mjs
import { build } from 'esbuild'
import path from 'node:path'

const here = path.dirname(new URL(import.meta.url).pathname)
const src = path.resolve(here, '../../src')

const stubs = {
  name: 'node-stubs',
  setup(b) {
    // Vite ?url assets (the pdf.js worker) are browser-only.
    b.onResolve({ filter: /\?url$/ }, (a) => ({ path: a.path, namespace: 'stub' }))
    b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({ contents: 'export default ""', loader: 'js' }))
    // The UI language: English on Apify.
    b.onResolve({ filter: /^@\/lib\/i18n$/ }, () => ({ path: 'i18n', namespace: 'i18n' }))
    b.onLoad({ filter: /.*/, namespace: 'i18n' }, () => ({
      contents: 'export const tr = (_id, en) => en; export const locale = () => "en-US"',
      loader: 'js',
    }))
    b.onResolve({ filter: /^@\// }, async (a) => b.resolve('./' + a.path.slice(2), { resolveDir: src, kind: a.kind }))
  },
}

await build({
  entryPoints: [path.join(here, 'engine/entry.ts')],
  outfile: path.join(here, 'src/engine.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  external: ['pdfjs-dist', 'pdfjs-dist/*', 'docx', 'exceljs'],
  plugins: [stubs],
  legalComments: 'none',
  banner: {
    js: '// GENERATED by build-engine.mjs from the toowl site source (src/tools/pdf-to-word, src/tools/pdf-to-excel). Do not edit.\n',
  },
  logLevel: 'info',
})
